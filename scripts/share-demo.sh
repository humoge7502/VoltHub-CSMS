#!/usr/bin/env bash
# scripts/share-demo.sh — give VoltHub CSMS a public, shareable HTTPS link.
#
# What it does (beginner mode: you run one command):
#   1. ensures the compose stack is up,
#   2. generates strong API/worker secrets in .env when they are missing or placeholders,
#   3. runs two cloudflared quick tunnels as Docker containers on the compose network
#      (web :3000, API :4000) — no host networking, works on Linux and Docker Desktop,
#   4. repoints the web build at the PUBLIC API origin (NEXT_PUBLIC_* is baked in) and
#      extends the API's CORS allow-list to the public web origin,
#   5. health-checks both public URLs, including a CORS preflight.
#
# Run from Git Bash on Windows or any POSIX shell on Linux/macOS:
#   bash scripts/share-demo.sh
#
# Re-running generates fresh URLs — quick tunnels are ephemeral by design. The URL is
# alive only while this machine and the tunnel containers stay online.
# Stop the tunnels with:  bash scripts/share-demo.sh --stop
# Stop everything with:   bash scripts/share-demo.sh --stop && docker compose -f infra/docker-compose.yml down
#
# Want a permanent URL? Use a named Cloudflare tunnel (DEPLOY.md §2) or a VM:
# this script is the free, zero-DNS, zero-VPS path for demos and sharing.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
COMPOSE_FILE="${ROOT}/infra/docker-compose.yml"
ENV_FILE="${ROOT}/.env"
CF_IMAGE="cloudflare/cloudflared:latest"
C_API="volthub-tunnel-api"
C_WEB="volthub-tunnel-web"

if ! command -v docker >/dev/null 2>&1; then
  echo "ERROR: docker not found — install it first: https://docs.docker.com/get-docker/" >&2
  exit 1
fi

compose() { docker compose --env-file "${ENV_FILE}" -f "${COMPOSE_FILE}" "$@"; }

get_env_key() { # key
  grep -E "^$1=" "${ENV_FILE}" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d '\r' || true
}

sed_inplace() {
  if sed --version >/dev/null 2>&1; then sed -i "$@"; else sed -i '' "$@"; fi
}

set_env_key() { # key value — idempotent, preserves the rest of .env
  local key="$1" val="$2"
  touch "${ENV_FILE}"
  if grep -qE "^${key}=" "${ENV_FILE}"; then
    sed_inplace "s|^${key}=.*|${key}=${val}|" "${ENV_FILE}"
  else
    printf '%s=%s\n' "${key}" "${val}" >>"${ENV_FILE}"
  fi
}

rand_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
  fi
}

ensure_secret() { # key — replace empty/placeholder/short values only
  local key="$1" cur
  cur="$(get_env_key "${key}")"
  if [ "${#cur}" -lt 32 ] || printf '%s' "${cur}" | grep -qE 'change_me|replace_|dev-only'; then
    set_env_key "${key}" "$(rand_hex)"
    echo "   generated ${key}"
  fi
}

stop_tunnels() {
  docker rm -f "${C_WEB}" "${C_API}" >/dev/null 2>&1 || true
}

if [ "${1:-}" = "--stop" ]; then
  stop_tunnels
  echo "Tunnels stopped."
  exit 0
fi

# ---------------------------------------------------------------- .env + secrets
if [ ! -f "${ENV_FILE}" ]; then
  echo "No .env found — creating one with safe defaults (DB passwords live in compose)."
  cat >"${ENV_FILE}" <<'EOF'
# Generated by scripts/share-demo.sh - never commit this file.
WEB_ORIGIN=http://localhost:3000,http://localhost:3120
TRUST_PROXY=1
NEXT_PUBLIC_API_BASE=http://localhost:4000/api/v1
NEXT_PUBLIC_SITE_URL=http://localhost:3000
# Uncomment to keep published ports off the LAN (Docker Desktop Windows may
# reject some loopback ports; the default binds all interfaces).
# BIND_ADDR=127.0.0.1
# Uncomment when another local Postgres already holds host port 5432.
# TS_HOST_PORT=15432
EOF
fi
ensure_secret JWT_SECRET
ensure_secret INTERNAL_TOKEN
set_env_key TRUST_PROXY 1

echo "== 1/6 compose stack =="
compose up -d
compose ps --format '{{.Name}}: {{.Status}}'

echo "== 2/6 tunnel image =="
docker image inspect "${CF_IMAGE}" >/dev/null 2>&1 || docker pull -q "${CF_IMAGE}" >/dev/null

echo "== 3/6 start tunnels on the compose network =="
NET="$(compose ps -q web | xargs -r docker inspect -f '{{range $k,$v := .NetworkSettings.Networks}}{{$k}}{{end}}' 2>/dev/null | tr -d '\r' | head -1)"
if [ -z "${NET}" ]; then NET="infra_default"; fi
stop_tunnels
docker run -d --name "${C_API}" --restart unless-stopped --network "${NET}" "${CF_IMAGE}" \
  tunnel --no-autoupdate --url http://api:4000 >/dev/null
docker run -d --name "${C_WEB}" --restart unless-stopped --network "${NET}" "${CF_IMAGE}" \
  tunnel --no-autoupdate --url http://web:3000 >/dev/null

wait_url() { # container — poll cloudflared logs for the trycloudflare URL
  local name="$1" url="" i
  for i in $(seq 1 60); do
    url="$(docker logs "${name}" 2>&1 | grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' | head -1 || true)"
    [ -n "${url}" ] && { echo "${url}"; return 0; }
    sleep 1
  done
  return 1
}

API_URL="$(wait_url "${C_API}")" || { echo "ERROR: API tunnel URL not found — docker logs ${C_API}" >&2; exit 1; }
WEB_URL="$(wait_url "${C_WEB}")" || { echo "ERROR: web tunnel URL not found — docker logs ${C_WEB}" >&2; exit 1; }
echo "   API: ${API_URL}"
echo "   Web: ${WEB_URL}"

echo "== 4/6 point the browser bundle and CORS at the public origins =="
# Keep local/custom origins, drop any previous quick-tunnel URL.
PREV_ORIGIN="$(get_env_key WEB_ORIGIN)"
KEPT_ORIGIN="$(printf '%s' "${PREV_ORIGIN}" | tr ',' '\n' | grep -v 'trycloudflare.com' | tr '\n' ',' | sed 's/,$//')"
if [ -z "${KEPT_ORIGIN}" ]; then KEPT_ORIGIN="http://localhost:3000,http://localhost:3120"; fi
set_env_key WEB_ORIGIN "${KEPT_ORIGIN},${WEB_URL}"
set_env_key NEXT_PUBLIC_API_BASE "${API_URL}/api/v1"
set_env_key NEXT_PUBLIC_SITE_URL "${WEB_URL}"

# API + worker must pick up WEB_ORIGIN / TRUST_PROXY / INTERNAL_TOKEN; the browser
# bundle needs a rebuild because NEXT_PUBLIC_* is inlined at build time.
compose up -d --force-recreate --no-deps api worker
compose up -d --build --no-deps web

echo "== 5/6 health checks =="
ok_api=0
ok_web=0
for _ in $(seq 1 45); do
  if curl -sf --max-time 10 "${API_URL}/api/v1/health" >/dev/null 2>&1; then ok_api=1; break; fi
  sleep 2
done
for _ in $(seq 1 45); do
  if curl -sf --max-time 10 "${WEB_URL}/" >/dev/null 2>&1; then ok_web=1; break; fi
  sleep 2
done
[ "${ok_api}" = 1 ] || echo "WARN: API public URL not responding yet — retry in a minute (docker logs ${C_API})"
[ "${ok_web}" = 1 ] || echo "WARN: web public URL not responding yet — retry in a minute (docker logs ${C_WEB})"

# Proves the browser's origin is accepted before you share the link.
CORS_OK=0
if CORS_HEADERS="$(curl -sS -D - -o /dev/null --max-time 10 -X OPTIONS \
  "${API_URL}/api/v1/auth/login" -H "Origin: ${WEB_URL}" \
  -H 'Access-Control-Request-Method: POST' 2>/dev/null)"; then
  if printf '%s' "${CORS_HEADERS}" | grep -qi "^access-control-allow-origin: ${WEB_URL}"; then CORS_OK=1; fi
fi
[ "${CORS_OK}" = 1 ] && echo "   CORS: ${WEB_URL} -> API allowed" || echo "WARN: CORS preflight did not echo ${WEB_URL} — check WEB_ORIGIN/docker logs volthub-api"

echo "== 6/6 done =="
cat <<EOF

==========================================================
  VoltHub CSMS is now PUBLIC — share these links:

    Console:  ${WEB_URL}
    API:      ${API_URL}/api/v1/health

  Demo logins:
    admin@volthub.in / Admin@123      (admin)
    arjun@volthub.in / Operator@123   (operator)
    any seeded driver / Driver@123

  Notes:
    - Quick-tunnel URLs change on each rerun and live only while this machine and
      the tunnel containers stay online.
    - Strong JWT_SECRET / INTERNAL_TOKEN generated in .env (gitignored).
    - Stop tunnels:  bash scripts/share-demo.sh --stop
    - Stop stack:    docker compose -f infra/docker-compose.yml down
    - For a permanent URL, use a named Cloudflare tunnel or a VM (DEPLOY.md §1–2).
==========================================================
EOF
exit 0
